[CmdletBinding()]
param(
    [string]$Root = (Split-Path $PSScriptRoot -Parent),
    [switch]$Check
)

$ErrorActionPreference = "Stop"

$schemaPath = Join-Path $Root "native\abi-contract.json"
$rustPath = Join-Path $Root "native\quicklook_next_native\src\abi_generated.rs"
$csharpPath = Join-Path $Root "src\QuickLook.Next.Core\NativeAbi.Generated.cs"
$signaturePath = Join-Path $Root "native\quicklook_next_native\src\abi_signatures_generated.rs"

if (-not (Test-Path -LiteralPath $schemaPath -PathType Leaf)) {
    throw "Missing native ABI schema: $schemaPath"
}

$schema = Get-Content -LiteralPath $schemaPath -Raw | ConvertFrom-Json
function Assert-SchemaInteger($Value, [string]$Name) {
    if ($Value -isnot [int] -and $Value -isnot [long]) {
        throw "$Name must be a JSON integer."
    }
}
Assert-SchemaInteger $schema.schemaVersion 'schemaVersion'
if ($schema.schemaVersion -cne 2) {
    throw "Unsupported native ABI schema version: $($schema.schemaVersion)"
}
if ($schema.callingConvention -cne 'C' -or $schema.target -cne 'x86_64-pc-windows-msvc') {
    throw 'Native ABI schema must describe the pinned win-x64 C calling convention.'
}

Assert-SchemaInteger $schema.nativeAbiVersion 'nativeAbiVersion'
$abiVersion = [int64]$schema.nativeAbiVersion
if ($abiVersion -le 0 -or $abiVersion -gt [uint32]::MaxValue) {
    throw "nativeAbiVersion must fit a positive u32."
}

$features = @($schema.features)
$statuses = @($schema.statuses)
if ($schema.features -isnot [Array] -or $schema.statuses -isnot [Array] -or
    $features.Count -eq 0 -or $statuses.Count -eq 0) {
    throw "Native ABI schema must declare features and statuses."
}

$rustNames = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
$csharpNames = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
$featureBits = [Collections.Generic.HashSet[int]]::new()
$statusValues = [Collections.Generic.HashSet[int]]::new()
$previousBit = -1

foreach ($feature in $features) {
    $rustName = [string]$feature.rust
    $csharpName = [string]$feature.csharp
    Assert-SchemaInteger $feature.bit 'feature.bit'
    $bit = [int]$feature.bit
    if ($rustName -notmatch '^QL_FEATURE_[A-Z0-9_]+$' -or
        $csharpName -notmatch '^[A-Z][A-Za-z0-9]+$') {
        throw "Invalid native ABI feature name: $rustName / $csharpName"
    }
    if ($bit -lt 0 -or $bit -gt 63 -or $bit -le $previousBit) {
        throw "Native ABI feature bits must be unique, ascending, and in the range 0-63."
    }
    if (-not $rustNames.Add($rustName) -or
        -not $csharpNames.Add($csharpName) -or
        -not $featureBits.Add($bit)) {
        throw "Native ABI feature names and bits must be unique."
    }
    $previousBit = $bit
}

foreach ($status in $statuses) {
    $rustName = [string]$status.rust
    $csharpName = [string]$status.csharp
    Assert-SchemaInteger $status.value 'status.value'
    $value = [int]$status.value
    if ($rustName -notmatch '^QL_(?:OK|ERROR_[A-Z0-9_]+)$' -or
        $csharpName -notmatch '^Status[A-Z][A-Za-z0-9]+$') {
        throw "Invalid native ABI status name: $rustName / $csharpName"
    }
    if (-not $rustNames.Add($rustName) -or
        -not $csharpNames.Add($csharpName) -or
        -not $statusValues.Add($value)) {
        throw "Native ABI status names and values must be unique."
    }
}
if (-not $statusValues.Contains(0) -or
    @($statuses | Where-Object { $_.rust -eq "QL_OK" -and [int]$_.value -eq 0 }).Count -ne 1) {
    throw "Native ABI statuses must contain exactly one QL_OK value of zero."
}

$rustLines = [Collections.Generic.List[string]]::new()
$rustLines.Add("// <auto-generated />")
$rustLines.Add("// Generated by tools/generate-native-abi.ps1 from native/abi-contract.json.")
$rustLines.Add("// Do not edit directly.")
$rustLines.Add("")
$rustLines.Add("const QL_NATIVE_ABI_VERSION: u32 = $abiVersion;")
$rustLines.Add("")
foreach ($feature in $features) {
    $rustLines.Add("const $($feature.rust): u64 = 1 << $([int]$feature.bit);")
}
$rustLines.Add("")
foreach ($status in $statuses) {
    $rustLines.Add("const $($status.rust): i32 = $([int]$status.value);")
}
$rustContent = [string]::Join("`n", $rustLines) + "`n"

$csharpLines = [Collections.Generic.List[string]]::new()
$csharpLines.Add("// <auto-generated />")
$csharpLines.Add("// Generated by tools/generate-native-abi.ps1 from native/abi-contract.json.")
$csharpLines.Add("// Do not edit directly.")
$csharpLines.Add("")
$csharpLines.Add("namespace QuickLook.Next.Core;")
$csharpLines.Add("")
$csharpLines.Add("public static partial class NativeAbi")
$csharpLines.Add("{")
$csharpLines.Add("    public const uint Version = $abiVersion;")
foreach ($feature in $features) {
    $csharpLines.Add("    public const ulong $($feature.csharp) = 1UL << $([int]$feature.bit);")
}
$csharpLines.Add("")
$csharpLines.Add("    // Stable status values for HANDLE entry points. Legacy path entry points retain their")
$csharpLines.Add("    // existing per-function return conventions until they are migrated.")
foreach ($status in $statuses) {
    $csharpLines.Add("    public const int $($status.csharp) = $([int]$status.value);")
}
$csharpLines.Add("}")
$csharpContent = [string]::Join("`n", $csharpLines) + "`n"

# This is a closed vocabulary, not arbitrary Rust source supplied by JSON.
$abiTypes = @{
    void = '()'; bool = 'bool'; i32 = 'i32'; i64 = 'i64'; u32 = 'u32'; u64 = 'u64'
    isize = 'isize'; usize = 'usize'; const_u8 = '*const u8'; const_u16 = '*const u16'
    mut_u8 = '*mut u8'; mut_usize = '*mut usize'; mut_u64 = '*mut u64'
}
$callbacks = @($schema.callbacks)
$exports = @($schema.exports)
if ($schema.callbacks -isnot [Array] -or $schema.exports -isnot [Array] -or
    $callbacks.Count -eq 0 -or $callbacks.Count -gt 16 -or
    $exports.Count -eq 0 -or $exports.Count -gt 1024) {
    throw 'Native ABI schema must contain bounded nonempty callbacks and exports.'
}
$callbackNames = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
$exportNames = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
$rustPaths = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
$signatureLines = [Collections.Generic.List[string]]::new()
$signatureLines.Add('// <auto-generated />')
$signatureLines.Add('// Generated by tools/generate-native-abi.ps1 from native/abi-contract.json.')
$signatureLines.Add('// Compile-time checks only: these constants add no exported functions or runtime work.')
$signatureLines.Add('')

function Get-AbiFunctionType($Entry, [switch]$Callback) {
    if ($Entry.safety -cnotin @('safe', 'unsafe') -or
        $Entry.rustPath -cnotmatch '^crate::(?:[a-z][a-z0-9_]*::)*[A-Za-z][A-Za-z0-9_]*$') {
        throw "Invalid native ABI safety or Rust path: $($Entry.name)"
    }
    $parameters = @($Entry.parameters)
    if ($Entry.parameters -isnot [Array] -or $parameters.Count -gt 32 -or
        [string]$Entry.returns -cnotin @($abiTypes.Keys)) {
        throw "Invalid native ABI parameters or return type: $($Entry.name)"
    }
    $parameterTypes = @($parameters | ForEach-Object {
        if ([string]$_ -cnotin @($abiTypes.Keys) -or $_ -ceq 'void' -or
            ($Callback -and $callbackNames.Contains([string]$_))) {
            throw "Invalid native ABI parameter type: $_ in $($Entry.name)"
        }
        $abiTypes[[string]$_]
    })
    $safetyPrefix = if ($Entry.safety -ceq 'unsafe') { 'unsafe ' } else { '' }
    return $safetyPrefix + 'extern "C" fn(' + ($parameterTypes -join ', ') + ') -> ' +
        $abiTypes[[string]$Entry.returns]
}

foreach ($callback in $callbacks) {
    if ($callback.name -cnotmatch '^[a-z][a-z0-9_]*_callback$' -or
        $abiTypes.ContainsKey([string]$callback.name) -or
        -not $callbackNames.Add([string]$callback.name) -or
        -not $rustPaths.Add([string]$callback.rustPath)) {
        throw "Duplicate or invalid native ABI callback: $($callback.name)"
    }
    $callbackType = Get-AbiFunctionType -Entry $callback -Callback
    $signatureLines.Add('#[rustfmt::skip]')
    $signatureLines.Add("const _: Option<$callbackType> = None::<$($callback.rustPath)>;")
    $abiTypes[[string]$callback.name] = "Option<$callbackType>"
}
$signatureLines.Add('')
$previousExport = ''
foreach ($export in $exports) {
    if ($export.name -cnotmatch '^ql_[a-z0-9_]+$' -or
        -not $exportNames.Add([string]$export.name) -or
        -not $rustPaths.Add([string]$export.rustPath) -or
        -not $export.rustPath.EndsWith('::' + $export.name, [StringComparison]::Ordinal) -or
        [StringComparer]::Ordinal.Compare($previousExport, [string]$export.name) -ge 0) {
        throw "Native ABI exports must have unique matching names/paths in ordinal order: $($export.name)"
    }
    if ($callbackNames.Contains([string]$export.returns)) {
        throw "Native ABI exports cannot return a callback: $($export.name)"
    }
    $signatureType = Get-AbiFunctionType -Entry $export
    $signatureLines.Add('#[rustfmt::skip]')
    $signatureLines.Add("const _: $signatureType = $($export.rustPath);")
    $previousExport = [string]$export.name
}
$capabilities = [uint64]0
foreach ($feature in $features) { $capabilities = $capabilities -bor ([uint64]1 -shl [int]$feature.bit) }
$signatureLines.Add('')
$signatureLines.Add('// Constant evaluation checks discovery without relying on source-body formatting.')
$signatureLines.Add("const _: () = assert!(crate::ffi::contract::ql_abi_version() == $($abiVersion)u32);")
$signatureLines.Add("const _: () = assert!(crate::ffi::contract::ql_capabilities() == $($capabilities)u64);")
$signatureLines.Add('')
$signatureLines.Add('#[cfg(test)]')
$signatureLines.Add('mod tests {')
$signatureLines.Add('    #[test]')
$signatureLines.Add('    fn discovery_matches_schema_exactly() {')
$signatureLines.Add("        assert_eq!(crate::ffi::contract::ql_abi_version(), $($abiVersion)u32);")
$signatureLines.Add("        assert_eq!(crate::ffi::contract::ql_capabilities(), $($capabilities)u64);")
$signatureLines.Add('        assert_eq!(crate::ffi::contract::ql_probe(17, 25), 42);')
$signatureLines.Add('        assert_eq!(crate::ffi::contract::ql_probe(2, -3), -1);')
$signatureLines.Add('        assert_eq!(crate::ffi::contract::ql_probe(0, 0), 0);')
$signatureLines.Add('        assert_eq!(crate::ffi::contract::ql_probe(i32::MAX, 0), i32::MAX);')
$signatureLines.Add('    }')
$signatureLines.Add('}')
$signatureContent = [string]::Join("`n", $signatureLines) + "`n"

$managedBindings = @($schema.managedBindings)
if ($schema.managedBindings -isnot [Array] -or $managedBindings.Count -eq 0 -or $managedBindings.Count -gt 64) {
    throw 'Native ABI schema must declare bounded managed bindings.'
}
$managedOwners = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
$managedDelegates = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
foreach ($binding in $managedBindings) {
    if ($binding.assembly -cnotmatch '^QuickLook\.Next\.(?:App|ParserHost|RasterHost|ShellBroker)$' -or
        $binding.type -cnotmatch '^[A-Za-z][A-Za-z0-9_]*(?:\.[A-Za-z][A-Za-z0-9_]*)+$' -or
        -not $binding.type.StartsWith($binding.assembly + '.', [StringComparison]::Ordinal) -or
        -not $managedOwners.Add([string]$binding.type) -or $binding.imports -isnot [Array] -or
        $binding.imports.Count -eq 0 -or $binding.imports.Count -gt 128 -or
        $binding.callbacks -isnot [pscustomobject] -or $binding.rawCallbackParameters -isnot [pscustomobject]) {
        throw 'Invalid managed ABI assembly/owner/import/callback inventory.'
    }
    $previousImport = ''
    foreach ($import in $binding.imports) {
        if ($import -cnotin @($exports | ForEach-Object name) -or
            [StringComparer]::Ordinal.Compare($previousImport, [string]$import) -ge 0) {
            throw "Managed ABI imports must reference unique ordered project exports: $import"
        }
        $previousImport = [string]$import
    }
    foreach ($callback in $binding.callbacks.PSObject.Properties) {
        if (-not $callbackNames.Contains($callback.Name) -or
            $callback.Value -cnotmatch '^[A-Za-z][A-Za-z0-9_]*(?:\.[A-Za-z][A-Za-z0-9_]*)+\+[A-Za-z][A-Za-z0-9_]*$' -or
            -not $callback.Value.StartsWith($binding.type + '+', [StringComparison]::Ordinal) -or
            -not $managedDelegates.Add([string]$callback.Value)) {
            throw "Invalid or duplicate managed ABI callback mapping: $($callback.Name)"
        }
    }
    foreach ($raw in $binding.rawCallbackParameters.PSObject.Properties) {
        $export = @($exports | Where-Object { $_.name -ceq $raw.Name })
        if ($raw.Name -cnotin $binding.imports -or $raw.Value -isnot [Array] -or $raw.Value.Count -eq 0) {
            throw 'Invalid managed ABI raw callback inventory.'
        }
        $previousIndex = -1
        foreach ($index in $raw.Value) {
            Assert-SchemaInteger $index 'raw callback index'
            if ($index -lt 0 -or $index -ge $export[0].parameters.Count -or $index -le $previousIndex -or
                -not $callbackNames.Contains([string]$export[0].parameters[$index]) -or
                $null -eq $binding.callbacks.($export[0].parameters[$index])) {
                throw 'Invalid managed ABI raw callback index/type.'
            }
            $previousIndex = $index
        }
    }
    foreach ($import in $binding.imports) {
        $export = @($exports | Where-Object { $_.name -ceq $import })[0]
        foreach ($type in $export.parameters) {
            if ($callbackNames.Contains([string]$type) -and $null -eq $binding.callbacks.$type) {
                throw "Missing managed ABI callback mapping: $type in $import"
            }
        }
    }
}
foreach ($assembly in @('QuickLook.Next.App', 'QuickLook.Next.ParserHost', 'QuickLook.Next.RasterHost', 'QuickLook.Next.ShellBroker')) {
    if (@($managedBindings | Where-Object { $_.assembly -ceq $assembly }).Count -eq 0) {
        throw "Missing required managed ABI assembly: $assembly"
    }
}

$dependencyExports = @($schema.dependencyExports)
if ($schema.dependencyExports -isnot [Array] -or $dependencyExports.Count -gt 16) {
    throw 'Native ABI schema must declare its bounded incidental dependency export inventory.'
}
foreach ($dependency in $dependencyExports) {
    $names = @($dependency.names)
    if ($dependency.package -cnotmatch '^[a-z][a-z0-9_-]*$' -or
        $dependency.version -cnotmatch '^\d+\.\d+\.\d+$' -or
        [string]::IsNullOrWhiteSpace($dependency.reason) -or
        $dependency.names -isnot [Array] -or $names.Count -eq 0 -or $names.Count -gt 256) {
        throw 'Invalid incidental dependency export package/version/reason/count.'
    }
    $previousName = ''
    foreach ($name in $names) {
        if ($name -cnotmatch '^[A-Za-z_][A-Za-z0-9_]*$' -or $name -cmatch '^ql_' -or
            -not $exportNames.Add([string]$name) -or
            [StringComparer]::Ordinal.Compare($previousName, [string]$name) -ge 0) {
            throw "Duplicate, unordered or invalid incidental dependency export: $name"
        }
        $previousName = [string]$name
    }
}

function Write-Or-CheckGeneratedFile(
    [string]$Path,
    [string]$ExpectedContent
) {
    if ($Check) {
        if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
            throw "Missing generated native ABI file: $Path"
        }
        $actualContent = [IO.File]::ReadAllText($Path)
        if ($actualContent -cne $ExpectedContent) {
            throw "Generated native ABI file is stale: $Path. Run tools/generate-native-abi.ps1."
        }
        return
    }

    $directory = Split-Path $Path -Parent
    if (-not (Test-Path -LiteralPath $directory -PathType Container)) {
        New-Item -ItemType Directory -Path $directory | Out-Null
    }
    [IO.File]::WriteAllText($Path, $ExpectedContent, [Text.UTF8Encoding]::new($false))
}

Write-Or-CheckGeneratedFile -Path $rustPath -ExpectedContent $rustContent
Write-Or-CheckGeneratedFile -Path $csharpPath -ExpectedContent $csharpContent
Write-Or-CheckGeneratedFile -Path $signaturePath -ExpectedContent $signatureContent

if ($Check) {
    Write-Host "native ABI generated files are current" -ForegroundColor Green
}
else {
    Write-Host "generated: $rustPath"
    Write-Host "generated: $csharpPath"
    Write-Host "generated: $signaturePath"
}
